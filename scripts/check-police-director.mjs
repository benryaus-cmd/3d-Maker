import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const file=new URL('../src/crime/.police-check.mjs',import.meta.url);
const sourceURL=new URL('../src/crime/PoliceDirector.ts',import.meta.url);
assert.ok(await fs.access(sourceURL).then(()=>true,()=>false),'PoliceDirector implementation exists');
try{
 const source=await fs.readFile(sourceURL,'utf8');
 await fs.writeFile(file,ts.transpileModule(source.replace("'./CityLayout'","'./CityLayout.ts'"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
 const {PoliceDirector,policeLineOfSight,createPoliceState,restorePoliceState}=await import(file.href);
 const wall={x:0,z:10,w:8,d:2};
 assert.equal(policeLineOfSight({x:0,z:0},{x:0,z:20},[wall]),false,'a wall breaks sight');
 assert.equal(policeLineOfSight({x:0,z:0},{x:0,z:20},[{...wall,broken:true}]),true,'destroyed walls do not block sight');
 assert.equal(policeLineOfSight({x:10,z:0},{x:10,z:20},[wall]),true,'a nearby wall does not block clear sight');
 const unit={id:'cop-1',x:0,z:0,heading:0};
 const input=(target={x:0,z:20,speed:10,onFoot:false},walls=[],units=[unit],safehouse=false)=>({target,units,walls,safehouse});
 const p=new PoliceDirector();p.reportIncident({x:0,z:20,severity:2,witnessId:'civilian'});
 assert.equal(p.step(0,input()).stage,'incident');
 assert.equal(p.step(1,input()).desiredUnitCount,0,'dispatch does not spawn units before report delay');
 assert.equal(p.step(1,input()).stage,'dispatch');
 let result=p.step(1,input());assert.equal(result.stage,'pursuit');assert.equal(result.guidance[0].visible,true);
 assert.equal(result.lastKnown.z,20);
 const hidden={x:0,z:30,speed:10,onFoot:false};result=p.step(2,input(hidden,[wall]));
 assert.equal(result.stage,'search');assert.equal(result.lastKnown.z,20,'occluded position never updates police knowledge');
 const searchGoal=result.guidance[0].destination;
 const clone=new PoliceDirector(p.snapshot());
 const farHidden={x:130,z:140,speed:10,onFoot:false};
 assert.deepEqual(clone.step(1,input(farHidden,[wall])).guidance,p.step(1,input(hidden,[wall])).guidance,'search guidance is independent of hidden target position');
 assert.ok(Number.isFinite(searchGoal.x));
 result=p.step(1,input());assert.equal(result.stage,'pursuit','clear sight reacquires target');
 result=p.step(1,input());assert.equal(result.canEnterSafehouse,false,'visible police block safehouse entry');
 const sheltered=new PoliceDirector();sheltered.reportIncident({x:0,z:3,severity:2});
 const lastKnown=sheltered.snapshot().lastKnown;
 for(let i=0;i<8;i++){
  const response=sheltered.step(1,input({x:0,z:2,speed:0,onFoot:true},[],[unit],true));
  assert.equal(response.arrested,false,'police cannot arrest sheltered actor via stale outdoor position');
  assert.ok(response.guidance.every(g=>!g.visible),'interior player is not visible outside');
  assert.deepEqual(response.lastKnown,lastKnown,'shelter cannot leak current position');
 }
 assert.equal(sheltered.stage,'search','police continue searching last known street after valid entry');
 result=p.step(2,input(hidden,[wall]));assert.equal(result.stage,'search');
 for(let i=0;i<40;i++)result=p.step(1,input(farHidden,[wall],[]));
 assert.equal(result.stage,'escaped');assert.equal(result.heat,0);assert.ok(result.notoriety>0,'vehicle notoriety survives escape');
 const arrested=new PoliceDirector();arrested.reportIncident({x:0,z:3,severity:2});
 const foot={x:0,z:3,speed:5,onFoot:true};arrested.step(3,input(foot));
 for(let i=0;i<5;i++)assert.equal(arrested.step(1,input(foot)).arrested,false,'moving foot target cannot be arrested via stationary parked-car speed');
 let a;for(let i=0;i<4;i++)a=arrested.step(1,input({...foot,speed:0}));assert.equal(a.arrested,true,'visible stationary foot target can be arrested');
 const delayArrest=new PoliceDirector();delayArrest.reportIncident({x:0,z:3,severity:2});
 assert.equal(delayArrest.step(3,input({...foot,speed:0})).arrested,false,'report wait cannot count toward arrest time');
 assert.equal(delayArrest.step(.4,input({...foot,speed:0})).arrested,false,'arrest timer begins only after police dispatch');
 const blocked=new PoliceDirector();blocked.reportIncident({x:0,z:3,severity:2});
 const smallWall={x:0,z:1.5,w:4,d:.5};for(let i=0;i<8;i++)assert.equal(blocked.step(1,input({...foot,speed:0},[smallWall])).arrested,false,'police cannot arrest through a wall');
 const state=p.snapshot(),frozen=JSON.stringify(state);p.step(0,input());assert.equal(JSON.stringify(p.snapshot()),frozen,'zero dt freezes simulation');
 const original=new PoliceDirector(state),restored=new PoliceDirector(JSON.parse(JSON.stringify(state)));
 for(let i=0;i<10;i++)assert.deepEqual(original.step(.25,input()),restored.step(.25,input()),'restored simulation advances deterministically');
 assert.deepEqual(restorePoliceState({heat:NaN,clock:-9,stage:'hacked'}),createPoliceState(),'invalid saved response is safely discarded');
 assert.equal(new PoliceDirector(undefined,2).heat,2,'legacy heat migrates into response');
 const high=new PoliceDirector();high.reportIncident({x:0,z:20,severity:4});
 result=high.step(3,input({x:0,z:20,speed:10,onFoot:false,vx:0,vz:10}));
 assert.ok(result.roadblock);assert.ok(result.roadblock.deployAt-result.roadblock.announcedAt>=6,'roadblock has meaningful warning lead time');
 const {STREET_NODES}=await import('../src/crime/CityLayout.ts');assert.ok(STREET_NODES.has(result.roadblock.nodeId),'roadblock uses real shared road node');
 assert.ok(Math.hypot(result.roadblock.x,result.roadblock.z-20)>=45,'roadblock placed ahead with room to respond');
 console.log('Police report, obstruction, search, escape, arrest, persistence and roadblock checks: PASS');
}finally{await fs.unlink(file).catch(()=>{});}
