const c=new Controls();
assert.equal(typeof c.setAim,'function','combat exposes independent aim input');
c.setStick(.6,.8);c.pointer(1,'throttle');c.pointerAim(2,1,0,true);
assert.equal(c.fire,true,'right thumb fires beyond deadzone');
assert.equal(c.aiming,true);assert.equal(c.aimX,1);assert.equal(c.aimZ,0);
assert.equal(c.moveX,.6);assert.equal(c.moveZ,.8);assert.equal(c.throttle,true);
c.release(2);assert.equal(c.fire,false,'right thumb release stops firing');
assert.equal(c.throttle,true,'right thumb release preserves left finger');assert.equal(c.moveX,.6);
c.pointerAim(2,0,0,false);assert.equal(c.fire,false,'aim deadzone never fires');
c.pointerAim(2,3,4,true);assert.equal(c.aimX,.6);assert.equal(c.aimZ,.8);
c.key('j',true);c.releaseAim(2);assert.equal(c.fire,true,'keyboard fire survives thumb release');
c.key('j',false);assert.equal(c.fire,false);
c.pointer(3,'fire');c.pointerAim(2,-1,0,true);c.release(3);assert.equal(c.fire,true,'fire sources stay independent');
c.pointer(4,'reload');c.key('r',true);c.release(4);assert.equal(c.reload,true);
c.key('r',false);assert.equal(c.reload,false);
c.clearAim();assert.equal(c.fire,false);assert.equal(c.aiming,false);assert.equal(c.moveX,.6);
c.setAim(Number.NaN,Infinity,true);assert.equal(c.aimX,0);assert.equal(c.aimZ,0);assert.equal(c.aiming,false,'invalid vectors cannot fire');
c.setAim(-1,0,true);c.key('j',true);c.key('r',true);c.clear();
for(const field of ['fire','reload','aiming','throttle','punch'])assert.equal(c[field],false,'focus/menu clear resets '+field);
for(const field of ['aimX','aimZ','moveX','moveZ','steer'])assert.equal(c[field],0);
c.release(1);c.releaseAim(2);assert.equal(c.fire,false,'late pointer capture release stays harmless');
